import {test,expect} from '@playwright/test';
import {enterGame,goWorkspace} from '../support/enterGame';
test('isolates automation, reads the companion while running, and resumes the genuine mandate',async({page})=>{
 await enterGame(page);
 await expect(page.getByRole('button',{name:'Executive Autopilot',exact:true})).toHaveCount(0);
 await page.getByRole('button',{name:/Practise bed-led leadership/}).click();
 // Simulate the persisted stage-two unlock without advancing this test's manual save.
 await page.evaluate(()=>localStorage.setItem('nothing-sim:campaign-profile','2'));
 await page.reload();
 const manual=await page.evaluate(()=>localStorage.getItem('nothing-sim:v1'));
 const awards=await page.evaluate(()=>localStorage.getItem('nothing-sim:achievement-profile'));
 await page.getByRole('button',{name:'Executive Autopilot',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Executive Autopilot™'})).toBeVisible();
 await page.getByRole('button',{name:'Run one campaign',exact:true}).click();
 await expect(page.getByTestId('auto-attempts')).toHaveText('1',{timeout:20000});
 await expect(page.getByTestId('auto-certified')).toHaveText('1');
 await expect(page.getByRole('region',{name:'Autopilot achievements'})).toContainText('Delegation Nation');
 await expect(page.getByTestId('auto-tokens')).toHaveText('0');
 await expect(page.getByRole('button',{name:'One million mandate'})).toBeEnabled();
 await page.getByRole('button',{name:'One million mandate'}).click();
 await expect(page.getByTestId('auto-mandate')).toContainText('1,000,000');
 await page.getByRole('button',{name:'Read The Art of Doing Nothing™'}).click();
 const reader=page.getByRole('main',{name:'Executive Library'});
 await expect(reader).toBeVisible();
 const count=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('nothing-sim:autopilot:v1')??'{}').attempts??0);
 const before=await count();
 await expect.poll(count,{timeout:20000}).toBeGreaterThan(before);
 await reader.getByRole('button',{name:/Return to Executive Autopilot/}).click();
 await page.getByRole('button',{name:'Pause automation'}).click();
 await expect(page.getByRole('button',{name:'Resume mandate'})).toBeVisible();
 const checkpoint=await count();
 await page.getByRole('button',{name:/Return to management/}).click();
 await expect(page.getByTestId('day')).toHaveText('001');
 expect(await page.evaluate(()=>localStorage.getItem('nothing-sim:v1'))).toBe(manual);
 expect(await page.evaluate(()=>localStorage.getItem('nothing-sim:achievement-profile'))).toBe(awards);
 await goWorkspace(page,'career');
 await expect(page.getByRole('article',{name:'Fictional executive CV'})).toContainText('Autonomous leadership (separate laboratory)');
 await page.reload();
 await page.getByRole('button',{name:'Executive Autopilot',exact:true}).click();
 expect(await count()).toBe(checkpoint);
 await page.getByRole('button',{name:'Resume mandate'}).click();
 await expect.poll(count,{timeout:20000}).toBeGreaterThan(checkpoint);
 await page.getByRole('button',{name:'Pause automation'}).click();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth)).toBe(false);
});
