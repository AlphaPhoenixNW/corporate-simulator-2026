import {test,expect} from '@playwright/test';
import {enterGame,goWorkspace} from '../support/enterGame';
test('introduces workspaces gradually with an optional full navigation and first-visit briefings',async({page})=>{
 await enterGame(page);
 const mobile=page.locator('#workspace-jump');
 const osOption=()=>mobile.locator('option[value="nothing-os"]');
 const osLink=()=>page.locator('a[data-route="nothing-os"]');
 if(await mobile.isVisible())await expect(osOption()).toHaveCount(0);else await expect(osLink()).toHaveCount(0);
 await page.getByRole('button',{name:/^Show all workspaces/}).click();
 if(await mobile.isVisible())await expect(osOption()).toHaveCount(1);else await expect(osLink()).toHaveCount(1);
 await page.reload();
 await expect(page.getByRole('button',{name:'Show recommended workspaces'})).toBeVisible();
 await goWorkspace(page,'nothing-os');
 const intro=page.getByRole('region',{name:'Workspace introduction'});
 await expect(intro).toContainText('Welcome to NOTHING™ OS');
 await expect(intro).toContainText('Watch out for');
 await intro.getByRole('button',{name:'Got it'}).click();
 await expect(intro).toHaveCount(0);
 await goWorkspace(page,'office');
 await goWorkspace(page,'nothing-os');
 await expect(intro).toHaveCount(0);
 await goWorkspace(page,'office');
 await page.getByRole('button',{name:'Show recommended workspaces'}).click();
 await page.getByRole('button',{name:/Conclude working day/}).click();
 const fresh=page.getByRole('region',{name:'New workspaces'});
 await expect(fresh).toBeVisible();
 await expect(fresh).toContainText('People');
 await expect(fresh).toContainText('Incidents');
 await fresh.getByRole('button',{name:'Dismiss introductions'}).click();
 await expect(fresh).toHaveCount(0);
 await goWorkspace(page,'employees');
 await expect(intro).toContainText('Welcome to People');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth)).toBe(false);
});
