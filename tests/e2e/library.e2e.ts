import {test,expect} from '@playwright/test';
test('read, navigate, bookmark and download the full book without changing the game',async({page})=>{
 await page.goto('/');
 await page.getByRole('button',{name:'Executive Library · Read the book'}).click();
 const reader=page.getByRole('main',{name:'Executive Library'});
 await expect(reader.getByRole('heading',{name:'The Art of Doing Nothing™',exact:true,level:1})).toBeVisible();
 await expect(reader.getByRole('img')).toBeVisible();
 expect(await reader.getByRole('img').evaluate((e:HTMLImageElement)=>e.complete&&e.naturalWidth>0)).toBe(true);
 const selector=reader.getByLabel('Reading section');
 await expect(selector.locator('option')).toHaveCount(22);
 await reader.getByRole('button',{name:'Table of contents'}).click();
 await reader.getByRole('navigation',{name:'Book contents'}).getByRole('button',{name:/Chapter 10/}).click();
 await expect(reader.getByRole('article')).toContainText('The Bed-Led Organisation™');
 await reader.getByRole('button',{name:'Larger text'}).click();
 await expect(reader).toHaveClass(/library-large/);
 await reader.getByRole('button',{name:'Next section'}).click();
 await expect(selector).toHaveValue('12');
 const download=page.waitForEvent('download');
 await reader.getByRole('button',{name:'Download complete book'}).click();
 expect((await download).suggestedFilename()).toBe('The Art of Doing Nothing - Companion Edition.html');
 await reader.getByRole('button',{name:/Return to title screen/}).click();
 await expect(page.getByRole('button',{name:'Continue simulation'})).toHaveCount(0);
 await page.getByRole('button',{name:'Play now',exact:true}).click();
 await page.getByRole('button',{name:/Practise bed-led leadership/}).click();
 await expect(page.getByTestId('cash')).toHaveText('£75,000');
 await page.getByRole('button',{name:'Executive Library',exact:true}).click();
 await expect(selector).toHaveValue('12');
 await selector.selectOption('21');
 await expect(reader.getByRole('button',{name:'Next section'})).toBeDisabled();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth)).toBe(false);
 await reader.getByRole('button',{name:/Return to simulation/}).click();
 await expect(page.getByTestId('day')).toHaveText('001');
 await expect(page.getByTestId('cash')).toHaveText('£75,000');
 await expect(page.locator('.compact-kpis')).toContainText('1/2');
 await page.reload();
 await page.getByRole('button',{name:'Executive Library',exact:true}).click();
 await expect(selector).toHaveValue('21');
});
