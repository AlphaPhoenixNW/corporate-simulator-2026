import {test,expect} from '@playwright/test';
import {enterGame,goWorkspace} from '../support/enterGame';
test('office exposes objectives and hides unrelated workspaces, with accessible navigation and retained state',async({page})=>{
 await enterGame(page);
 const brief=page.getByRole('region',{name:"Today's objectives"});
 await expect(brief).toBeVisible();await expect(brief).toContainText('Perceived productivity');
 await expect(brief).toContainText('Schedule alignment workshop');
 await expect(page.getByRole('region',{name:'Corporate finance'})).toHaveCount(0);
 await expect(page.getByRole('region',{name:'NOTHING™ OS Enterprise Edition'})).toHaveCount(0);
 await expect(page.locator('.workspace-view:not([hidden])')).toHaveCount(1);
 await page.getByRole('button',{name:/Schedule alignment workshop/}).click();
 await expect(page.getByTestId('cash')).toHaveText('£74,400');
 await goWorkspace(page,'finance');
 await expect(page.getByRole('region',{name:'Corporate finance'})).toBeVisible();
 await expect(brief).toHaveCount(0);
 await expect(page.getByRole('button',{name:/Schedule alignment workshop/})).toHaveCount(0);
 await page.reload();
 await expect(page.getByRole('region',{name:'Corporate finance'})).toBeVisible();
 await expect(page.getByTestId('cash')).toHaveText('£74,400');
 await goWorkspace(page,'office');await expect(brief).toBeVisible();
 await page.getByRole('button',{name:/Conclude working day/}).click();
 await expect(page.getByRole('region',{name:'Pending corporate decision'})).toBeVisible();
 await goWorkspace(page,'finance');
 await expect(page.getByRole('region',{name:'Pending corporate decision'})).toBeVisible();
 await expect(page.getByRole('button',{name:/Conclude working day/})).toBeDisabled();
 await page.getByRole('region',{name:'Pending corporate decision'}).getByRole('button').first().click();
 await expect(page.getByRole('button',{name:/Conclude working day/})).toBeEnabled();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth)).toBe(false);
});
